#STRING METHODS
#11.Convert a string to uppercase
a = "python developer"
print(a.upper())
print(a.lower())#12.convert a string to lowercase
print(a.capitalize())#13.Capitalize the first character
print(a.title())#14.Convert every word to title case
print(a.swapcase())#15.Swap uppercase and lowercase

#16.Remove spaces from the beginning and end
a = "   python developer   "
print(a.strip())

#17. Replace a word in a string
a = "I am learning java"
print(a.replace("java","python"))

#18. Count the occurrence of a character
a = "programming"
print(a.count("m"))

#19. Find the position of a character
a = "python"
print(a.find("t"))

#20. Check whether a string starts and ends with specific characters
a = "python"
print(a.startswith("py"))
print(a.endswith("on"))

